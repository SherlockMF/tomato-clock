function takesSlowTrain(s) {
  return s.ledger.some(row => row.n === 25 && row.amount === -80);
}

function sharedStall(s) {
  return s.choices[31] === 'stall';
}

function choseLetter(s, n, letter) {
  return s.trace.some(row => row.n === n && row.letter === letter);
}

