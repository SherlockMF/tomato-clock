export const bedPrices={room:280,dorm:70+3*20,workstay:70};
export const shiftWage=60, mealsAfterLodging=180;
export function hasMorningShifts(s){
  return s.choices[34]==='workstay'||s.ledger.some(row=>row.n===34&&row.amount===-120);
}
export function lodging(s,key){
  const cashOnArrival=s.balance-s.ledger.filter(row=>row.n>=34).reduce((sum,row)=>sum+row.amount,0);
  const work=key==='workstay';
  // Previously opened check-ins keep the rates and the two offers they actually saw.
  const dorm=key==='dorm'||(!s.bedOffers&&!work&&cashOnArrival-bedPrices.room-mealsAfterLodging<238);
  const cost=s.bedOffers?(s.bedOffers[key]??bedPrices[key]):work?120:dorm?130:280;
  return {cost,dorm,remaining:cashOnArrival-cost-mealsAfterLodging+(work?2*shiftWage:0)};
}
