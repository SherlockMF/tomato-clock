// Keep a scene inside its original focus receipt when moving its time for a real activity.
export function withinReceipt(day:number,original:number,minute:number){
  const offset=(day-1)*960;
  const end=Math.ceil((offset+original)/200)*200-offset;
  return Math.max(1,end-199,Math.min(959,end,minute));
}

